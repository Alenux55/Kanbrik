CREATE FUNCTION enforce_personal_membership() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE owner_id TEXT; workspace_kind "WorkspaceKind";
BEGIN
  SELECT "personalOwnerId", kind INTO owner_id, workspace_kind FROM "Workspace" WHERE id = NEW."workspaceId";
  IF workspace_kind = 'personal' AND (NEW."userId" <> owner_id OR NEW.role <> 'owner') THEN
    RAISE EXCEPTION 'Personal membership must be its owner' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER personal_membership_guard BEFORE INSERT OR UPDATE ON "Membership"
FOR EACH ROW EXECUTE FUNCTION enforce_personal_membership();
