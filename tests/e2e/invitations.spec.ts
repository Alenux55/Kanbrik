import { randomUUID } from "node:crypto";
import { hashPassword } from "better-auth/crypto";
import { test, expect } from "./base";
import { testDB } from "../database";

const origin = "http://127.0.0.1:3108";
test("administrator emails an account-only invitation while public signup stays closed", async ({ page, request, context, testAccounts, isMobile }) => {
  const adminEmail = "browser-invitation-admin@example.invalid";
  const recipient = `${randomUUID()}@example.invalid`;
  testAccounts.push(adminEmail, recipient);
  const id = randomUUID(), password = randomUUID() + randomUUID();
  await testDB.user.create({ data: { id, name: "Invitation administrator", email: adminEmail, accounts: { create: { id: randomUUID(), accountId: id, providerId: "credential", password: await hashPassword(password) } } } });
  await page.goto(origin + "/sign-up");
  await expect(page.getByText("Registration is disabled.", { exact: false })).toBeVisible();
  await page.goto(origin + "/sign-in");
  await page.getByLabel("Email", { exact: true }).fill(adminEmail);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(origin + "/projects");
  await page.goto(origin + "/settings");
  const panel = page.getByRole("region", { name: "Account invitations", exact: true });
  await panel.getByLabel("Invitation email").fill(recipient);
  const send = panel.getByRole("button", { name: "Send account invitation", exact: true });
  if (isMobile) await send.tap(); else { await send.focus(); await page.keyboard.press("Enter"); }
  await expect(panel.getByRole("status")).toContainText("Invitation sent");
  await expect(panel.getByText(recipient, { exact: true })).toBeVisible();
  const captured = await request.get(`http://127.0.0.1:3126/messages?to=${encodeURIComponent(recipient)}`, { headers: { "x-test-mail-secret": process.env.TEST_MAIL_SECRET! } });
  const messages = await captured.json();
  expect(messages).toHaveLength(1);
  const link = messages[0].text.match(/http[^\s]+/)[0] as string;
  // Acceptance may not create another account inside an existing session.
  await page.goto(link);
  await expect(page).toHaveURL(origin + "/accept-invitation");
  await page.getByLabel("Name", { exact: true }).fill("Invited user");
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByLabel("Confirm your password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Create invited account", exact: true }).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("Sign out first");
  await context.clearCookies();
  await page.goto(link);
  await expect(page).toHaveURL(origin + "/accept-invitation");
  await page.getByLabel("Name", { exact: true }).fill("Invited user");
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByLabel("Confirm your password", { exact: true }).fill("different-password");
  await page.getByRole("button", { name: "Create invited account", exact: true }).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("Passwords do not match");
  await page.getByLabel("Confirm your password", { exact: true }).fill(password);
  expect(new URL(page.url()).hash).toBe("");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Create invited account", exact: true }).click();
  await expect(page.getByRole("main").getByRole("status")).toContainText("Your account has been created");
  await page.getByRole("link", { name: "Back to sign in", exact: true }).click();
  await page.getByLabel("Email", { exact: true }).fill(recipient);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(origin + "/projects");
  const spaces = await page.evaluate(async () => (await fetch("/api/workspaces")).json());
  expect(spaces).toHaveLength(1); expect(spaces[0].kind).toBe("personal");
  await page.goto(origin + "/settings");
  await expect(page.getByRole("heading", { name: "User settings", exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "Account invitations", exact: true })).toHaveCount(0);
  const denied = await page.evaluate(async () => (await fetch("/api/invitations")).status);
  expect(denied).toBe(403);
});
